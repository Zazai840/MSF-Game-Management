import { expect,join,lookProblems,test } from './fixtures.js';
test('probe',async({page},info)=>{
  const seen:Record<string,unknown>={};
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Join the Running Zone'})).toBeVisible();
  seen.join=await lookProblems(page);
  await page.screenshot({path:info.outputPath('join.png'),fullPage:true});
  await join(page,'wrong',{code:'nope'});
  await expect(page.getByRole('alert')).toBeVisible();
  seen.wrong=await page.getByRole('alert').textContent();
  await join(page,`Probe ${info.project.name}`,{job:'Start line'});
  await expect(page.getByRole('navigation',{name:'Event type'})).toBeVisible();
  seen.races=await lookProblems(page);
  await page.screenshot({path:info.outputPath('races.png'),fullPage:true});
  await page.getByRole('button',{name:'New race'}).click();
  seen.sheet=await lookProblems(page);
  await page.screenshot({path:info.outputPath('newrace.png'),fullPage:true});
  await page.getByRole('button',{name:'60m',exact:true}).click();
  await page.getByRole('button',{name:/^Girl Cubs/}).click();
  await page.getByRole('button',{name:/^Create heat/}).click();
  await expect(page.getByRole('heading',{level:1,name:'60m · Girl Cubs'})).toBeVisible();
  seen.start=await lookProblems(page);
  await page.screenshot({path:info.outputPath('start.png'),fullPage:true});
  expect(seen).toEqual({});
});
